class Country {
  final String name;
  final String code; // ISO 3166-1 alpha-2
  const Country(this.name, this.code);
}

/// Returns the emoji flag for a given ISO 3166-1 alpha-2 country code.
String countryFlag(String code) {
  if (code.length != 2) return '🌍';
  final int base = 0x1F1E6; // Regional Indicator Symbol Letter A
  final upper = code.toUpperCase();
  final first = upper.codeUnitAt(0) - 0x41 + base; // 'A' is 0x41
  final second = upper.codeUnitAt(1) - 0x41 + base;
  return String.fromCharCode(first) + String.fromCharCode(second);
}

/// Returns phone dial code (E.164) for a given ISO 3166-1 alpha-2 country code.
/// If not found, returns an empty string.
String dialCodeFor(String iso2) {
  final code = iso2.toUpperCase();
  return countryDialCodes[code] ?? '';
}

